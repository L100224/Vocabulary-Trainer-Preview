const SUPPORTED_LANGUAGES = ['de', 'en', 'es', 'fr', 'it'];

function detectInitialLanguage() {
    const saved = localStorage.getItem('vocab_ui_lang');
    if (saved && SUPPORTED_LANGUAGES.includes(saved)) {
        return saved;
    }
    const navLang = (navigator.language || navigator.userLanguage || 'de').slice(0, 2).toLowerCase();
    if (SUPPORTED_LANGUAGES.includes(navLang)) {
        return navLang;
    }
    return 'de';
}

let currentUiLang = detectInitialLanguage();

function t(key, params = {}) {
    const langDict = TRANSLATIONS[currentUiLang] || TRANSLATIONS['de'];
    let val = langDict[key] !== undefined ? langDict[key] : (TRANSLATIONS['de'][key] !== undefined ? TRANSLATIONS['de'][key] : key);

    if (typeof val === 'function') {
        return val(params);
    }

    let text = String(val);
    for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
    return text;
}

// Helfer: Liefert den Namen der Muttersprache in der eigenen Sprache ("Deutsch", "English", "Español"...)
function getNativeLanguageName() {
    return t('native_lang_name');
}

// Helfer: Liefert den lokalisierten Namen einer Fremdsprache anhand des Sprachcodes
function getLocalizedLanguageName(langCode, fallbackName = '') {
    if (!langCode) return fallbackName || t('default_foreign_lang');
    const clean = langCode.replace('-', '_');
    const key = `lang_${clean}`;
    const langDict = TRANSLATIONS[currentUiLang] || TRANSLATIONS['de'];
    if (langDict[key]) return langDict[key];
    return fallbackName || langCode;
}

function formatDays(count) {
    const langDict = TRANSLATIONS[currentUiLang] || TRANSLATIONS['de'];
    return langDict.format_days ? langDict.format_days(count) : `${count} Tage`;
}

function formatLessons(count) {
    const langDict = TRANSLATIONS[currentUiLang] || TRANSLATIONS['de'];
    return langDict.format_lessons ? langDict.format_lessons(count) : `${count} Lektionen`;
}

function formatDuration(ms) {
    const totalSec = Math.max(1, Math.round(ms / 1000));
    const mins = Math.floor(totalSec / 60);
    const secs = totalSec % 60;
    const langDict = TRANSLATIONS[currentUiLang] || TRANSLATIONS['de'];
    const sLabel = langDict.sec_short || 's';
    if (mins === 0) {
        return `${secs} ${sLabel}`;
    }
    return `${mins}:${String(secs).padStart(2, '0')}`;
}

function applyUiTranslations() {
    document.documentElement.lang = currentUiLang;

    // Textinhalte
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = t(key);
    });

    // Platzhalter
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = t(key);
    });

    // Tooltips & Titel
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.title = t(key);
    });
}

function setUiLanguage(langCode) {
    if (!SUPPORTED_LANGUAGES.includes(langCode)) return;
    currentUiLang = langCode;
    localStorage.setItem('vocab_ui_lang', langCode);
    applyUiTranslations();

    window.dispatchEvent(new CustomEvent('uiLanguageChanged', { detail: { lang: langCode } }));
}